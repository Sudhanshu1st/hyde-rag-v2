"""Free-quota plan: how many days of Groq free-tier quota each planned run needs.

Reads configs/quota_plan.yaml and configs/llm.yaml and writes docs/QUOTA_PLAN.md.
Models run in parallel (each has its own daily limits), so the wall-clock estimate
for a phase is the busiest model's total, not the sum.

Usage:
    python scripts/estimate_quota.py
    python scripts/estimate_quota.py --role judge=openai/gpt-oss-120b --out -
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from hyde_rag.llm.quota import estimate_run, load_limits  # noqa: E402


def family(model: str) -> str:
    return "qwen" if "qwen" in model else "gpt-oss"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--plan", type=Path, default=REPO_ROOT / "configs" / "quota_plan.yaml")
    parser.add_argument("--llm", type=Path, default=REPO_ROOT / "configs" / "llm.yaml")
    parser.add_argument(
        "--role", action="append", default=[], help="override, e.g. judge=openai/gpt-oss-120b"
    )
    parser.add_argument(
        "--out", default=str(REPO_ROOT / "docs" / "QUOTA_PLAN.md"), help="path or - for stdout"
    )
    args = parser.parse_args()

    plan = yaml.safe_load(args.plan.read_text(encoding="utf-8"))
    roles = dict(yaml.safe_load(args.llm.read_text(encoding="utf-8"))["roles"])
    for override in args.role:
        key, value = override.split("=", 1)
        roles[key] = value
    limits = load_limits(args.llm)

    rows = []
    by_phase_model: dict[tuple[int, str], list[float]] = defaultdict(lambda: [0.0, 0.0])
    by_model: dict[str, list[float]] = defaultdict(lambda: [0.0, 0.0])
    for run in plan["runs"]:
        model = roles[run["role"]]
        calls = run["calls"] if "calls" in run else run["queries"] * run["samples"]
        per_call = plan["tokens_per_call"][run["task"]][family(model)]
        est = estimate_run(limits[model], model, calls, per_call)
        rows.append((run["phase"], run["id"], model, est))
        for acc in (by_phase_model[(run["phase"], model)], by_model[model]):
            acc[0] += est.tokens
            acc[1] += est.requests

    def days(model: str, tokens: float, requests: float) -> float:
        lim = limits[model]
        return max(tokens / lim.tpd, requests / lim.rpd)

    lines = [
        "# Free-quota plan",
        "",
        "Generated by `scripts/estimate_quota.py` from `configs/quota_plan.yaml` and `configs/llm.yaml`.",
        "Money spent: **0**. The only constraint is each model's free daily quota "
        "(Groq free plan, 200K tokens and 1K requests per model per day).",
        "Token figures are planning assumptions until 20-call pilots measure them.",
        "",
        "| Phase | Run | Model | Requests | Tokens | Days of quota |",
        "|---:|---|---|---:|---:|---:|",
    ]
    for phase, run_id, model, est in rows:
        lines.append(
            f"| {phase} | {run_id} | `{model}` | {est.requests:,} | {est.tokens:,} | {est.days:.1f} |"
        )

    lines += [
        "",
        "## Wall-clock by phase (models run in parallel)",
        "",
        "| Phase | Busiest model | Days |",
        "|---:|---|---:|",
    ]
    phases = sorted({p for p, _ in by_phase_model})
    total_days = 0.0
    for phase in phases:
        per_model = {m: days(m, *by_phase_model[(phase, m)]) for (p, m) in by_phase_model if p == phase}
        busiest = max(per_model, key=per_model.get)
        total_days += per_model[busiest]
        lines.append(f"| {phase} | `{busiest}` | {per_model[busiest]:.1f} |")
    lines.append(f"| **all** | | **{total_days:.1f}** |")

    lines += [
        "",
        "## Load per model (all phases)",
        "",
        "| Model | Requests | Tokens | Days |",
        "|---|---:|---:|---:|",
    ]
    for model, (tok, req) in sorted(by_model.items()):
        lines.append(f"| `{model}` | {int(req):,} | {int(tok):,} | {days(model, tok, req):.1f} |")
    text = "\n".join(lines) + "\n"

    if args.out != "-":
        Path(args.out).write_text(text, encoding="utf-8")
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
