"""Planning-stage cost estimate for every bulk LLM run in configs/run_plan.yaml.

Input tokens for BEIR runs come from the real query lengths in data/beir
(chars / chars_per_token + prompt overhead). Output tokens come from the plan's
assumptions until pilots replace them. Writes docs/COST_PLAN.md.

Usage:
    python scripts/estimate_cost.py
    python scripts/estimate_cost.py --role answerer=claude-opus-5-5 --out -
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from hyde_rag.llm.cost import estimate_cost, load_pricing  # noqa: E402


def mean_query_chars(beir_dir: Path, dataset: str, split: str, max_queries: int | None) -> tuple[int, float]:
    ds = beir_dir / dataset
    qrels = (ds / "qrels" / f"{split}.tsv").read_text(encoding="utf-8").splitlines()[1:]
    qids = sorted({line.split("\t", 1)[0] for line in qrels})
    if max_queries:
        qids = qids[:max_queries]
    wanted = set(qids)
    lengths = []
    with (ds / "queries.jsonl").open(encoding="utf-8") as f:
        for line in f:
            obj = json.loads(line)
            if obj["_id"] in wanted:
                lengths.append(len(obj["text"]))
    return len(lengths), sum(lengths) / len(lengths)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--plan", type=Path, default=REPO_ROOT / "configs" / "run_plan.yaml")
    parser.add_argument("--beir-dir", type=Path, default=REPO_ROOT / "data" / "beir")
    parser.add_argument(
        "--role", action="append", default=[], help="override a role, e.g. answerer=claude-opus-5-5"
    )
    parser.add_argument(
        "--out", default=str(REPO_ROOT / "docs" / "COST_PLAN.md"), help="output path, or - for stdout"
    )
    args = parser.parse_args()

    plan = yaml.safe_load(args.plan.read_text(encoding="utf-8"))
    pricing = load_pricing()
    roles = dict(plan["roles"])
    for override in args.role:
        key, value = override.split("=", 1)
        roles[key] = value
    cpt = float(plan["chars_per_token"])

    rows = []
    per_phase: dict[int, float] = defaultdict(float)
    per_model: dict[str, float] = defaultdict(float)
    for run in plan["runs"]:
        model = roles[run["role"]]
        if "dataset" in run:
            n_q, q_chars = mean_query_chars(
                args.beir_dir, run["dataset"], run["split"], run.get("max_queries")
            )
            n_calls = n_q * run["samples"]
            in_tok = q_chars / cpt + run["prompt_overhead"]
            out_tok = plan["output_tokens"][run["output"]][model]
        else:
            n_calls, in_tok, out_tok = run["n_calls"], run["input_tokens"], run["output_tokens"]
        est = estimate_cost(pricing, model, n_calls, in_tok, out_tok, batch=True)
        rows.append((run["phase"], run["id"], model, n_calls, est.input_tokens, est.output_tokens, est.usd))
        per_phase[run["phase"]] += est.usd
        per_model[model] += est.usd

    subtotal = sum(per_phase.values())
    contingency = subtotal * plan["contingency"]
    lines = [
        "# Cost plan (planning estimate)",
        "",
        f"Generated by `scripts/estimate_cost.py` from `configs/run_plan.yaml` and `configs/pricing.yaml` "
        f"(prices verified {pricing.verified}, Batch API = {pricing.batch_discount:.0%} of list).",
        "Input tokens for BEIR runs use real query lengths; "
        "output tokens are assumptions until pilots measure them.",
        "",
        "Roles: " + ", ".join(f"`{k}`={v}" for k, v in roles.items()),
        "",
        "| Phase | Run | Model | Calls | Input tok | Output tok | USD (batch) | > $5 limit? |",
        "|---:|---|---|---:|---:|---:|---:|:---:|",
    ]
    for phase, run_id, model, n, tin, tout, usd in rows:
        flag = "yes" if usd > 5 else ""
        lines.append(f"| {phase} | {run_id} | {model} | {n:,} | {tin:,} | {tout:,} | {usd:,.2f} | {flag} |")
    lines += ["", "| Phase | USD |", "|---:|---:|"]
    lines += [f"| {p} | {v:,.2f} |" for p, v in sorted(per_phase.items())]
    lines += [
        f"| subtotal | {subtotal:,.2f} |",
        f"| contingency ({plan['contingency']:.0%}) | {contingency:,.2f} |",
        f"| **total** | **{subtotal + contingency:,.2f}** |",
        "",
        "| Model | USD |",
        "|---|---:|",
    ]
    lines += [f"| {m} | {v:,.2f} |" for m, v in sorted(per_model.items(), key=lambda kv: -kv[1])]
    text = "\n".join(lines) + "\n"

    if args.out == "-":
        sys.stdout.write(text)
    else:
        Path(args.out).write_text(text, encoding="utf-8")
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
