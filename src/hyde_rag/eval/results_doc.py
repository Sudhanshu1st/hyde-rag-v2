"""Build docs/RESULTS.md and the README headline table from results/ (no numbers typed by hand).

Every value comes from results/<experiment>/metrics.json (and generation metrics). The only
hand-typed values are the paper's published references in configs/headline.yaml.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from hyde_rag import paths
from hyde_rag.eval.report import render_table

README_START = "<!-- results:start (generated by `hyde-rag results`; do not edit) -->"
README_END = "<!-- results:end -->"


def _load(experiment: str) -> dict | None:
    path = paths.results_dir() / experiment / "metrics.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _cell(m: dict | None, system: str, metric: str = "ndcg@10") -> str:
    if not m or system not in m["systems"]:
        return "-"
    v = m["systems"][system]["metrics"][metric]
    star = ""
    if "p_holm" in v and system.startswith("hyde-"):  # stars only for HyDE vs its encoder baseline
        star = "**" if v["p_holm"] < 0.01 else "*" if v["p_holm"] < 0.05 else ""
    return f"{100 * v['mean']:.1f}{star}"


def headline_table() -> str:
    spec = yaml.safe_load((paths.CONFIG_DIR / "headline.yaml").read_text(encoding="utf-8"))
    data = {d: _load(d) for d in spec["datasets"]}
    head = "| System | " + " | ".join(f"{d} nDCG@10 (ours / paper)" for d in spec["datasets"])
    head += " | LLM tokens / query | CPU ms / query |"
    lines = [head, "|---|" + "---:|" * (len(spec["datasets"]) + 2)]
    for row in spec["rows"]:
        cells = []
        for d in spec["datasets"]:
            paper = row.get("paper", {}).get(d)
            cells.append(f"{_cell(data[d], row['system'])} / {paper if paper is not None else '-'}")
        ref = next(
            (
                data[d]["systems"][row["system"]]
                for d in spec["datasets"]
                if data[d] and row["system"] in data[d]["systems"]
            ),
            None,
        )
        tokens = (
            "-" if not ref or ref["llm_tokens_per_query"] is None else f"{ref['llm_tokens_per_query']:,.0f}"
        )
        cpu = "-" if not ref or ref["retrieval_ms"] is None else f"{ref['retrieval_ms']:,.0f}"
        lines.append(f"| {row['label']} | " + " | ".join(cells) + f" | {tokens} | {cpu} |")
    lines += [
        "",
        "\\* p < 0.05, \\*\\* p < 0.01 vs the same encoder without HyDE (paired randomisation, "
        "Holm-corrected). Tokens and CPU time are from SciFact. All LLM calls on free tiers: $0.",
    ]
    return "\n".join(lines)


def judge_note(j: dict, faithfulness: dict[str, float | None]) -> str:
    """How far to trust the faithfulness judge, from the human labels (D-EVAL-8)."""
    from hyde_rag.eval.judge_validation import corrected_faithfulness

    rates = j.get("human_supported_rate_given_judge", {})
    note = (
        f"Judge vs human labels: agreement {j['agreement']:.2f}, Cohen's kappa {j['cohen_kappa']:.2f} on "
        f"{j['n_labelled']} claims (balanced sample)."
    )
    if rates.get("supported") is not None and rates.get("not_supported") is not None:
        fixed = {s: corrected_faithfulness(f, j) for s, f in faithfulness.items() if f is not None}
        note += (
            f" People agreed with {rates['supported']:.0%} of the judge's 'supported' verdicts but only "
            f"{1 - rates['not_supported']:.0%} of its 'not supported' ones, so judge faithfulness is a lower "
            "bound; re-weighted by the human labels it is "
            + ", ".join(f"{v:.2f} ({s})" for s, v in fixed.items())
            + " (D-EVAL-8)."
        )
    return note


def generation_table() -> str:
    m = _load("scifact-generation")
    if not m:
        return "_Not run yet._"
    keys = [
        ("verdict_accuracy", "Verdict accuracy"),
        ("faithfulness", "Faithfulness (judge)"),
        ("citation_precision", "Citation precision"),
        ("citation_validity", "Valid citations: every sentence"),
        ("citation_grounded", "Valid citations: every answer"),
        ("abstention_recall", "Abstention recall"),
        ("abstention_precision", "Abstention precision"),
        ("false_refusal_rate", "False refusals"),
        ("tokens_per_answer", "Tokens / answer"),
    ]
    systems = list(m["systems"])
    lines = ["| Metric | " + " | ".join(systems) + " |", "|---|" + "---:|" * len(systems)]
    for k, label in keys:
        vals = []
        for s in systems:
            v = m["systems"][s].get(k)
            vals.append("-" if v is None else (f"{v:,.0f}" if k == "tokens_per_answer" else f"{v:.2f}"))
        lines.append(f"| {label} | " + " | ".join(vals) + " |")
    judge = paths.results_dir() / "scifact-generation" / "judge_validation.json"
    if judge.exists():
        j = json.loads(judge.read_text(encoding="utf-8"))
        lines += ["", judge_note(j, {s: m["systems"][s].get("faithfulness") for s in systems})]
    else:
        lines += ["", "_Faithfulness is the LLM judge's score; human validation pending._"]
    lines += [
        "",
        f"{m['n_claims']} claims, answerer `{m['answerer']}`, judge `{m['judge']}`, "
        f"top-{m['top_k']} context; abstention gate τ = {m['gate']['tau']:.3f} (dev split).",
    ]
    return "\n".join(lines)


def food_generation_table() -> str:
    m = _load("food-generation")
    if not m:
        return "_Not run yet._"
    systems = list(m["systems"])
    keys = [
        ("correctness", "Correctness (1 / 0.5 / 0)"),
        ("correct_rate", "Fully correct"),
        ("faithfulness", "Faithfulness (judge)"),
        ("citation_precision", "Citation precision"),
        ("citation_validity", "Valid citations: every sentence"),
        ("citation_grounded", "Valid citations: every answer"),
        ("abstention_recall", "Abstention recall"),
        ("abstention_precision", "Abstention precision"),
        ("false_refusal_rate", "False refusals"),
        ("tokens_per_answer", "Tokens / answer"),
    ]
    lines = ["| Metric | " + " | ".join(systems) + " |", "|---|" + "---:|" * len(systems)]
    for k, label in keys:
        vals = []
        for s in systems:
            v = m["systems"][s].get(k)
            vals.append("-" if v is None else (f"{v:,.0f}" if k == "tokens_per_answer" else f"{v:.2f}"))
        lines.append(f"| {label} | " + " | ".join(vals) + " |")
    types = sorted({t for s in systems for t in (m["systems"][s].get("correctness_by_type") or {})})
    if types:
        lines += ["", "Correctness by question type:", ""]
        lines += ["| Type | " + " | ".join(systems) + " |", "|---|" + "---:|" * len(systems)]
        for t in types:
            vals = [m["systems"][s].get("correctness_by_type", {}).get(t) for s in systems]
            lines.append(f"| {t} | " + " | ".join("-" if v is None else f"{v:.2f}" for v in vals) + " |")
    gates = ", ".join(
        f"{s} τ = {g['tau']:.3f}"
        if g["tau"] is not None
        else f"{s}: gate off (no τ within the false-refusal cap)"
        for s, g in m.get("gates", {}).items()
    )
    lines += [
        "",
        f"{m['n_questions']} test questions (every unanswerable one plus answerable ones stratified by "
        f"type), answerer `{m['answerer']}`, judge `{m['judge']}`, top-{m['top_k']} context; abstention "
        f"gates calibrated on the dev split: {gates}.",
    ]
    judge = paths.results_dir() / "scifact-generation" / "judge_validation.json"
    if judge.exists():
        j = json.loads(judge.read_text(encoding="utf-8"))
        lines.append(
            judge_note(j, {s: m["systems"][s].get("faithfulness") for s in systems})
            + " Same judge model and prompt as SciFact; the correctness grading is not human-validated."
        )
    audit = paths.REPO_ROOT / "eval_sets" / "food_quality" / "audit.json"
    if audit.exists():
        a = json.loads(audit.read_text(encoding="utf-8"))
        lines.append(
            f"The eval set is LLM-reviewed; a human audit of {a['n_labelled']} review decisions agreed "
            f"with {a['agreement']:.0%} of them (D-EVAL-7)."
        )
    else:
        lines.append("The eval set is LLM-reviewed; the human audit of the review is pending (D-EVAL-7).")
    return "\n".join(lines)


def build(write_readme: bool = True) -> Path:
    parts = [
        "# Results",
        "",
        "Generated by `uv run hyde-rag results` from `results/`. Do not edit by hand.",
        "",
        "## Headline",
        "",
        headline_table(),
        "",
        "## Grounded generation (SciFact)",
        "",
        generation_table(),
        "",
        "## Grounded answers (food safety)",
        "",
        food_generation_table(),
    ]
    for exp in ("scifact", "trec-covid", "scifact-dev", "food-test", "food-dev"):
        table = paths.results_dir() / exp / "metrics.json"
        if table.exists():
            parts += ["", f"## {exp}: all systems", "", render_table(table)]
    out = paths.REPO_ROOT / "docs" / "RESULTS.md"
    out.write_text("\n".join(parts) + "\n", encoding="utf-8")
    if write_readme:
        readme = paths.REPO_ROOT / "README.md"
        text = readme.read_text(encoding="utf-8")
        block = f"{README_START}\n{headline_table()}\n{README_END}"
        if README_START in text:
            text = re.sub(
                re.escape(README_START) + ".*?" + re.escape(README_END), lambda _: block, text, flags=re.S
            )
            readme.write_text(text, encoding="utf-8")
    return out
